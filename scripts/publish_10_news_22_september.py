def create_banner(src_img_path, dst_filename, badge_text, headline_text, subtext):
    dst_webp_path = os.path.join(IMG_DIR, dst_filename)
    if not os.path.exists(src_img_path):
        src_img_path = os.path.join(BASE_DIR, 'static', 'images', 'hero', 'sugarcane-field.jpg')
    
    with Image.open(src_img_path) as img:
        img = img.convert('RGB')
        target_w, target_h = 1200, 675
        src_w, src_h = img.size
        target_ratio = target_w / target_h
        src_ratio = src_w / src_h

        if src_ratio > target_ratio:
            new_w = int(src_h * target_ratio)
            left = (src_w - new_w) // 2
            img = img.crop((left, 0, left + new_w, src_h))
        else:
            new_h = int(src_w / target_ratio)
            top = (src_h - new_h) // 2
            img = img.crop((0, top, src_w, top + new_h))

        img = img.resize((target_w, target_h), Image.Resampling.LANCZOS)
        
        banner_h = 250
        overlay = Image.new('RGBA', (1200, banner_h), (10, 16, 26, 235))
        img.paste(overlay, (0, target_h - banner_h), overlay)
        
        draw = ImageDraw.Draw(img)
        
        try:
            font_badge = ImageFont.truetype(FONT_PATH, 26, index=0)
            font_headline = ImageFont.truetype(FONT_PATH, 42, index=0)
            font_sub = ImageFont.truetype(FONT_PATH, 30, index=0)
        except Exception:
            font_badge = ImageFont.truetype(FONT_PATH, 26)
            font_headline = ImageFont.truetype(FONT_PATH, 42)
            font_sub = ImageFont.truetype(FONT_PATH, 30)

        # Red accent bar
        draw.rectangle([0, target_h - banner_h, target_w, target_h - banner_h + 8], fill=(220, 38, 38))
        
        # Yellow badge
        badge_bbox = draw.textbbox((0, 0), badge_text, font=font_badge)
        badge_w = badge_bbox[2] - badge_bbox[0] + 30
        draw.rounded_rectangle([40, target_h - banner_h + 20, 40 + badge_w, target_h - banner_h + 65], radius=6, fill=(245, 158, 11))
        draw.text((55, target_h - banner_h + 26), badge_text, font=font_badge, fill=(15, 23, 42))

        # Headline
        draw.text((40, target_h - banner_h + 82), headline_text, font=font_headline, fill=(255, 255, 255))
        
        # Subtext
        draw.text((40, target_h - banner_h + 165), subtext, font=font_sub, fill=(251, 191, 36))

        img.save(dst_webp_path, 'WEBP', quality=88)
        print(f"Created banner: {dst_filename}")

